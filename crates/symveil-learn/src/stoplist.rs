//! Programming vocabulary and keywords dropped from name and symbol candidates.
//!
//! Secret, email, host, and address spans are not filtered through this list.

use std::sync::LazyLock;

static STOPPED: LazyLock<std::collections::HashSet<&'static str>> =
    LazyLock::new(|| WORDS.iter().copied().collect());

pub fn is_stopped(word: &str) -> bool {
    let lower = word.to_ascii_lowercase();
    STOPPED.contains(lower.as_str())
}

/// Ordinary words and the synthetic benign list. They stay candidates so
/// `[v]` can show them, and they stay hidden until then.
pub fn is_common(word: &str) -> bool {
    let lower = word.to_lowercase();
    COMMON.iter().any(|item| *item == lower)
}

